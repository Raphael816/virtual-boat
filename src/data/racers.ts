export type Grade = 'A1' | 'A2' | 'B1' | 'B2';

export interface Racer {
  id: string;
  name: string;
  /** 所属支部（都道府県名を一般名称として使用） */
  branch: string;
  grade: Grade;
  age: number;
  /** 体重 (kg)。軽いほど直線で有利だが、波には弱い */
  weight: number;
  /** 全国勝率（表示用。能力から算出） */
  winRate: number;
  /** 全国2連対率 (%) */
  quinellaRate: number;
  /** 平均スタートタイミング（秒） */
  avgST: number;
  /** 能力値 0-100 */
  start: number;
  turn: number;
  speed: number;
  wave: number;
  note: string;
}

