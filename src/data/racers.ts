function rates(s: Seed): { winRate: number; quinellaRate: number } {
  const ability = (s[6] * 0.3 + s[7] * 0.45 + s[8] * 0.25 - 60) / 35; // 0〜1 付近
  return {
    winRate: Math.round((3.8 + ability * 4.4) * 100) / 100,
    quinellaRate: Math.round(18 + ability * 42),
  };
}

